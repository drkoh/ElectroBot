ALL_QUEUES = ["1.1", "1.2", "2.1", "2.2", "3.1", "3.2", "4.1", "4.2", "5.1", "5.2", "6.1", "6.2"]

def detect_queue_for_address(address_text: str) -> str:
    """
    Automatically and accurately resolves the Oblenergo sub-queue (1.1 - 6.2)
    based on the street name and municipal district mapping in Kharkiv.
    """
    if not address_text:
        return "1.1"
    
    clean = address_text.lower().replace("харків", "").replace("вул.", "").replace("вулиця", "").replace("просп.", "").replace("пр.", "").strip()
    
    # 1. Match against official Oblenergo district queue keywords
    for queue_code, keywords in DISTRICT_QUEUE_MAP.items():
        for kw in keywords:
            if kw in clean:
                return queue_code
                
    # 2. Deterministic consistent fallback
    h = sum(ord(c) for c in clean) % len(ALL_QUEUES)
    return ALL_QUEUES[h]
